const dicts: Record<Lang, Dict> = { en, sv, es, fr, ar }
const pluralRules = new Map<Lang, Intl.PluralRules>()

function pick(lang: Lang, entry: Entry, n: number | undefined): string {
  if (typeof entry === 'string') return entry
  if (n === undefined) return entry.other
  let rules = pluralRules.get(lang)
  if (!rules) pluralRules.set(lang, (rules = new Intl.PluralRules(lang)))
  return entry[rules.select(n)] ?? entry.other
}

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  const entry = dicts[lang][key] ?? en[key]
  const n = typeof vars?.n === 'number' ? vars.n : undefined
  let s = pick(lang, entry, n)
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, typeof v === 'number' ? v.toLocaleString(lang) : v)
    }
  }
  return s
}

export function useT() {
  const lang = useApp((s) => s.lang)
  return (key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars)
}

const ERROR_KEYS: Record<string, TKey> = {
  'wrong passphrase': 'errWrongPassphrase',
  'not a lawha key backup': 'errBadBackup',
  'seed must be 32 bytes': 'errBadBackup',
}

export function translateError(lang: Lang, message: string): string {
  const key = ERROR_KEYS[message]
  return key ? translate(lang, key) : message
}

